    /** Hash {@code in[off, off + len)} and return the 32-byte digest. */
    public static byte[] hash(byte[] in, int off, int len) {
        byte[] out = new byte[32];
        hash(in, off, len, out, 0);
        return out;
    }

    /** Hash {@code in[off, off + len)} and write the 32-byte digest to {@code out[outOff, outOff + 32)}. */
    public static void hash(byte[] in, int off, int len, byte[] out, int outOff) {
        if (off < 0 || len < 0 || off > in.length - len) throw new IndexOutOfBoundsException();
        // s[0, 8) is the chain value h, s[8, 24) the working vector v, s[24, 40) the message block m.
        // Parameter block word 0: digest length 32, key length 0, fanout 1, depth 1.
        long[] s = new long[40];
        s[0] = IV0 ^ 0x01010020L;
        s[1] = IV1;
        s[2] = IV2;
        s[3] = IV3;
        s[4] = IV4;
        s[5] = IV5;
        s[6] = IV6;
        s[7] = IV7;
        int pos = off;
        int rem = len;
        while (rem > BLOCK) {
            for (int i = 0; i < 16; i++) s[24 + i] = (long) LE.get(in, pos + 8 * i);
            pos += BLOCK;
            rem -= BLOCK;
            compress(s, pos - off, false);
        }
        // Last block, zero-padded. A length of 0 still compresses one all-zero block.
        int words = rem >>> 3;
        for (int i = 0; i < words; i++) s[24 + i] = (long) LE.get(in, pos + 8 * i);
        for (int i = words; i < 16; i++) s[24 + i] = 0L;
        for (int i = words << 3; i < rem; i++) s[24 + words] |= (in[pos + i] & 0xffL) << ((i & 7) << 3);
        compress(s, len, true);
        LE.set(out, outOff, s[0]);
        LE.set(out, outOff + 8, s[1]);
        LE.set(out, outOff + 16, s[2]);
        LE.set(out, outOff + 24, s[3]);
    }

    /** The compression function F of RFC 7693 §3.2. {@code t} is the byte count so far; its high word is always 0. */
    private static void compress(long[] s, long t, boolean last) {
        System.arraycopy(s, 0, s, 8, 8);
        s[16] = IV0;
        s[17] = IV1;
        s[18] = IV2;
        s[19] = IV3;
        s[20] = IV4 ^ t;
        s[21] = IV5;
        s[22] = last ? ~IV6 : IV6;
        s[23] = IV7;
        roundsLow(s);
        roundsHigh(s);
        for (int i = 0; i < 8; i++) s[i] ^= s[8 + i] ^ s[16 + i];
    }

